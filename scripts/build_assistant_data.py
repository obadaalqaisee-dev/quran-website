"""Build assets/data/quran-tafsir.json, the knowledge file of the site assistant.

It contains, for each of the 6,236 ayahs: the global id, surah, ayah number, the Uthmani text (displayed), the
simple text (searched) and Tafsir al-Muyassar (searched and displayed). It is generated only from the verified
datasets in backend/app/data, after checking their SHA-256 checksums, so the assistant can never show text that
differs from the site's verified Quran and tafsir. Run from the repository root:

    python3 scripts/build_assistant_data.py
"""

from __future__ import annotations

import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "backend" / "app" / "data"
OUT = ROOT / "assets" / "data" / "quran-tafsir.json"
INPUTS = ["ayahs.json.gz", "edition-ar.muyassar.json.gz"]


def verified(name: str) -> bytes:
    raw = (DATA / name).read_bytes()
    expected = json.loads((DATA / "checksums.json").read_text())[name]
    actual = hashlib.sha256(raw).hexdigest()
    if actual != expected:
        raise SystemExit(f"{name}: checksum mismatch ({actual} != {expected}); refusing to build")
    return raw


def main() -> None:
    ayahs = json.loads(gzip.decompress(verified(INPUTS[0])))
    tafsir = json.loads(gzip.decompress(verified(INPUTS[1])))
    cols = ayahs["columns"]
    idx = {c: cols.index(c) for c in ("id", "surah", "number_in_surah", "text_uthmani", "text_simple")}
    rows = ayahs["rows"]
    texts = tafsir["texts"]
    if len(rows) != 6236 or len(texts) != 6236:
        raise SystemExit("unexpected dataset size")
    out_rows = []
    for i, r in enumerate(rows):
        if r[idx["id"]] != i + 1:
            raise SystemExit(f"non-contiguous id at row {i}")
        out_rows.append([r[idx["id"]], r[idx["surah"]], r[idx["number_in_surah"]], r[idx["text_uthmani"]], r[idx["text_simple"]], texts[i]])
    doc = {
        "about": "Quran (Tanzil Uthmani + simple) and Tafsir al-Muyassar, generated by scripts/build_assistant_data.py",
        "tafsir": {"identifier": tafsir["identifier"], "name": tafsir["name"]},
        "sources": {name: json.loads((DATA / "checksums.json").read_text())[name] for name in INPUTS},
        "columns": ["id", "surah", "ayah", "uthmani", "simple", "tafsir"],
        "rows": out_rows,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes, {len(out_rows)} ayahs)")


if __name__ == "__main__":
    main()
